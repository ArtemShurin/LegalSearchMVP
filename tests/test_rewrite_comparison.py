def ollama_generate_silent(prompt: str) -> str:
    """Генерация без стриминга — для batch-теста."""
    payload = json.dumps({
        "model": MODEL,
        "prompt": prompt,
        "stream": False,
        "options": {"temperature": 0.1, "num_predict": 128},
    }).encode()
    req = urllib.request.Request(
        f"{OLLAMA_URL}/api/generate",
        data=payload,
        headers={"Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            data = json.loads(resp.read())
            return data.get("response", "").strip()
    except urllib.error.URLError as e:
        print(f"ОШИБКА Ollama: {e}")
        sys.exit(1)


def check_ollama():
    try:
        with urllib.request.urlopen(f"{OLLAMA_URL}/api/tags", timeout=5) as resp:
            data = json.loads(resp.read())
            models = [m["name"] for m in data.get("models", [])]
            if not any(MODEL in m for m in models):
                print(f"ОШИБКА: модель '{MODEL}' не найдена. Запустите: ollama pull {MODEL}")
                sys.exit(1)
            print(f"Ollama OK  |  модель '{MODEL}' доступна\n")
    except urllib.error.URLError:
        print(f"ОШИБКА: Ollama не запущена ({OLLAMA_URL}). Запустите: ollama serve")
        sys.exit(1)


def get_top_score(query: str, embedder, reranker, client) -> tuple[float, str]:
    """Возвращает (топ-1 reranker score, название первого документа)."""
    sys.path.insert(0, "tests")
    from test_pipeline import search
    results = search(query, embedder, reranker, client, silent=True)
    if not results:
        return -99.0, "—"
    score, hit = results[0]
    title = hit.payload.get("title", "—")[:60]
    return float(score), title



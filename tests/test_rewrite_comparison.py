    improved      = sum(1 for r in results if r["delta"] > 0)
    degraded      = sum(1 for r in results if r["delta"] < -0.5)
    avg_delta     = sum(r["delta"] for r in results) / len(results)

    print(f"  Прошли порог 2.0 БЕЗ rewriting:  {passed_before}/{total}")
    print(f"  Прошли порог 2.0 С rewriting:     {passed_after}/{total}")
    print(f"  Улучшились (delta > 0):           {improved}/{total}")
    print(f"  Ухудшились (delta < -0.5):        {degraded}/{total}")
    print(f"  Среднее изменение score:          {avg_delta:+.2f}")
    print()

    # По отраслям
    from collections import defaultdict
    by_area = defaultdict(list)
    for r in results:
        by_area[r["area"]].append(r)

    print("  По отраслям:")
    for area, rs in sorted(by_area.items()):
        avg_orig = sum(r["score_original"] for r in rs) / len(rs)
        avg_new  = sum(r["score_rewritten"] for r in rs) / len(rs)
        print(f"    {area:<18} avg {avg_orig:5.2f} → {avg_new:5.2f}  (n={len(rs)})")

    print()

    if args.save:
        out = {
            "test": "rewrite_comparison",
            "date": time.strftime("%Y-%m-%d %H:%M"),
            "model_llm": MODEL,
            "total_queries": total,
            "summary": {
                "passed_before": passed_before,
                "passed_after": passed_after,
                "improved": improved,
                "degraded": degraded,
                "avg_delta": round(avg_delta, 3),
            },
            "results": results,
        }
        with open(args.save, "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
        print(f"  Результаты сохранены: {args.save}")



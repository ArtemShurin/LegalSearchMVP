def ollama_generate_silent(prompt: str, max_tokens: int = 512) -> tuple[str, float]:
    """Генерация без стриминга, возвращает (текст, время_сек)."""
    payload = json.dumps({
        "model": MODEL,
        "prompt": prompt,
        "stream": False,
        "options": {"temperature": 0.1, "num_predict": max_tokens},
    }).encode()
    req = urllib.request.Request(
        f"{OLLAMA_URL}/api/generate",
        data=payload,
        headers={"Content-Type": "application/json"},
    )
    t0 = time.time()
    try:
        with urllib.request.urlopen(req, timeout=120) as resp:
            data = json.loads(resp.read())
            return data.get("response", "").strip(), time.time() - t0
    except urllib.error.URLError as e:
        print(f"ОШИБКА Ollama: {e}")
        sys.exit(1)


def check_ollama():
    try:
        with urllib.request.urlopen(f"{OLLAMA_URL}/api/tags", timeout=5) as resp:
            data = json.loads(resp.read())
            models = [m["name"] for m in data.get("models", [])]
            if not any(MODEL in m for m in models):
                print(f"ОШИБКА: модель '{MODEL}' не найдена. Запустите: ollama pull {MODEL}")
                sys.exit(1)
            print(f"Ollama OK  |  модель '{MODEL}' доступна\n")
    except urllib.error.URLError:
        print(f"ОШИБКА: Ollama не запущена ({OLLAMA_URL}). Запустите: ollama serve")
        sys.exit(1)


def has_article_reference(text: str) -> bool:
    """Проверяет, есть ли в тексте ссылки на статьи/нормы."""
    patterns = [
        r'стать[яи]\s+\d+',
        r'ст\.\s*\d+',
        r'п\.\s*\d+',
        r'ч\.\s*\d+',
        r'\[\d+\]',
        r'ТК РФ|ГК РФ|УК РФ|КоАП|ЖК РФ|СК РФ|НК РФ',
    ]
    return any(re.search(p, text, re.IGNORECASE) for p in patterns)


def has_no_answer_phrase(text: str) -> bool:
    """Проверяет, сказала ли модель 'нет информации'."""
    phrases = ["не содержится", "нет информации", "нет прямого", "не упоминается",
               "не могу ответить", "отсутствует", "не указано"]
    text_lower = text.lower()
    return any(p in text_lower for p in phrases)



    no_art   = [r for r in scored if not r.get("has_articles") and not r.get("no_answer")]
    no_ans   = [r for r in scored if r.get("no_answer")]

    avg_score = sum(r["top_score"] for r in scored) / len(scored) if scored else 0
    avg_llm   = sum(r["llm_sec"] for r in scored) / len(scored) if scored else 0

    print(f"  Найдено документов (score >= 2.0):   {len(scored)}/{total}")
    print(f"  Заблокировано порогом:               {len(failed)}/{total}")
    print(f"  Ответы с конкретными статьями (✅):   {len(concrete)}/{len(scored)}")
    print(f"  Ответы без ссылок на статьи (⚠️):    {len(no_art)}/{len(scored)}")
    print(f"  Ответы 'нет информации' (❌):         {len(no_ans)}/{len(scored)}")
    print(f"  Средний score топ-1:                 {avg_score:.2f}")
    print(f"  Среднее время LLM:                   {avg_llm:.1f}с")
    print()

    print("  По отраслям:")
    from collections import defaultdict
    by_area = defaultdict(list)
    for r in results:
        by_area[r["area"]].append(r)
    for area, rs in sorted(by_area.items()):
        s_rs = [r for r in rs if r["top_score"]]
        avg_s = sum(r["top_score"] for r in s_rs) / len(s_rs) if s_rs else 0
        c = sum(1 for r in s_rs if r.get("has_articles") and not r.get("no_answer"))
        print(f"    {area:<18} avg_score={avg_s:5.2f}  concrete={c}/{len(rs)}")

    if args.save:
        out = {
            "test": "strong_zone_llm_quality",
            "date": time.strftime("%Y-%m-%d %H:%M"),
            "model_llm": MODEL,
            "total_queries": total,
            "summary": {
                "found": len(scored),
                "failed_threshold": len(failed),
                "concrete_answers": len(concrete),
                "no_article_answers": len(no_art),
                "no_answer": len(no_ans),
                "avg_top_score": round(avg_score, 2),
                "avg_llm_sec": round(avg_llm, 2),
            },
            "results": results,
        }
        with open(args.save, "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
        print(f"\n  Результаты сохранены: {args.save}")



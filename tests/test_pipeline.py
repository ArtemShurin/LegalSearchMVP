def main():
    parser = argparse.ArgumentParser(description="Тест search pipeline (embed → retrieve → rerank)")
    parser.add_argument("query", nargs="?", help="Поисковый запрос. Если не указан — запускаются тестовые запросы.")
    parser.add_argument("--top", type=int, default=DEFAULT_RERANK_TOP_K, help=f"Кол-во результатов (по умолчанию {DEFAULT_RERANK_TOP_K})")
    parser.add_argument("--device", default="cpu", choices=["cpu", "cuda"], help="Устройство для инференса")
    parser.add_argument("--qdrant", default=QDRANT_URL, help=f"URL Qdrant (по умолчанию {QDRANT_URL})")
    parser.add_argument("--ood", action="store_true", help="Запустить out-of-domain тест (нерелевантные запросы)")
    args = parser.parse_args()

    # Проверяем доступность Qdrant
    try:
        client = QdrantClient(url=args.qdrant, timeout=10)
        collections = client.get_collections().collections
        names = [c.name for c in collections]
        if COLLECTION not in names:
            print(f"ОШИБКА: коллекция '{COLLECTION}' не найдена в Qdrant.")
            print(f"Доступные коллекции: {names}")
            sys.exit(1)
        info = client.get_collection(COLLECTION)
        print(f"Qdrant OK  |  коллекция '{COLLECTION}'  |  {info.points_count:,} векторов\n")
    except Exception as e:
        print(f"ОШИБКА: не удалось подключиться к Qdrant по адресу {args.qdrant}")
        print(f"  {e}")
        print("\nУбедитесь что Docker запущен: docker compose up -d qdrant")
        sys.exit(1)

    embedder, reranker = load_models(device=args.device)

    if args.query:
        queries = [args.query]
        results = search(args.query, embedder, reranker, client, top_k=args.top)
        print_results(args.query, results)
        return

    if args.ood:
        queries = OUT_OF_DOMAIN_QUERIES
        print("=" * 70)
        print("ТЕСТ OUT-OF-DOMAIN (нерелевантные запросы)")
        print("=" * 70 + "\n")
    else:
        queries = TEST_QUERIES

    for q in queries:
        results = search(q, embedder, reranker, client, top_k=args.top)
        print_results(q, results)


if __name__ == "__main__":
    main()

def load_models(device: str = "cpu"):
    """Тонкая обёртка над ml.models.load_models() — тест грузит ТЕ ЖЕ модели
    тем же кодом, что и прод, а не отдельную копию (раньше дублировали)."""
    t0 = time.time()
    _ml_load_models(device=device)
    print(f"      модели загружены за {time.time() - t0:.1f}с\n")
    return get_embedder(), get_reranker()


def search(query: str, embedder, reranker, client: QdrantClient, top_k: int = DEFAULT_RERANK_TOP_K, silent: bool = False):
    # 1. Embed
    t0 = time.time()
    vector = embedder.encode(f"query: {query}", normalize_embeddings=True).tolist()
    embed_ms = (time.time() - t0) * 1000

    # 2. Retrieve
    t0 = time.time()
    hits = client.search(
        collection_name=COLLECTION,
        query_vector=vector,
        limit=RETRIEVE_TOP_K,
        with_payload=True,
    )
    retrieve_ms = (time.time() - t0) * 1000

    if not hits:
        if not silent:
            print("Qdrant вернул 0 результатов.")
        return []

    # 3. Rerank
    t0 = time.time()
    pairs = [(query, hit.payload.get("text", "")) for hit in hits]
    scores = reranker.predict(pairs)
    rerank_ms = (time.time() - t0) * 1000

    ranked = sorted(zip(scores, hits), key=lambda x: x[0], reverse=True)

    # 4. Дедупликация по doc_id, берём top_k уникальных документов
    results = []
    seen = set()
    for score, hit in ranked:
        doc_id = hit.payload.get("doc_id", "")
        if doc_id in seen:
            continue
        seen.add(doc_id)
        results.append((score, hit))
        if len(results) >= top_k:
            break

    # 5. Порог релевантности — если лучший score ниже порога, считаем запрос вне домена
    if results and results[0][0] < RELEVANCE_THRESHOLD:
        if not silent:
            print(f"Время: embed={embed_ms:.0f}мс  retrieve={retrieve_ms:.0f}мс  rerank={rerank_ms:.0f}мс\n")
            print(f"  [порог не пройден: топ-1 score={results[0][0]:.2f} < {RELEVANCE_THRESHOLD}]\n")
        return []

    if not silent:
        print(f"Время: embed={embed_ms:.0f}мс  retrieve={retrieve_ms:.0f}мс  rerank={rerank_ms:.0f}мс\n")
    return results


def print_results(query: str, results: list):
    print(f"{'='*70}")
    print(f"Запрос: {query}")
    print(f"{'='*70}")
    if not results:
        print("Ничего не найдено.\n")
        return

    for i, (score, hit) in enumerate(results, 1):
        p = hit.payload
        title = p.get("title", "—")
        doc_type = p.get("doc_type", "—")
        date = p.get("date", "—")
        text = p.get("text", "")[:300].replace("\n", " ").strip()
        doc_id = p.get("doc_id", "—")

        print(f"\n[{i}] {title}")
        print(f"    Тип: {doc_type}  |  Дата: {date}  |  doc_id: {doc_id}")
        print(f"    Reranker score: {score:.4f}")
        print(f"    Фрагмент: {text}...")
    print()



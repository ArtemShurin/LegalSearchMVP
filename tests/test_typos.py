def ollama_generate_silent(prompt: str) -> str:
    payload = json.dumps({
        "model": MODEL,
        "prompt": prompt,
        "stream": False,
        "options": {"temperature": 0.1, "num_predict": 128},
    }).encode()
    req = urllib.request.Request(
        f"{OLLAMA_URL}/api/generate",
        data=payload,
        headers={"Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(req, timeout=60) as resp:
            data = json.loads(resp.read())
            return data.get("response", "").strip()
    except urllib.error.URLError as e:
        print(f"ОШИБКА Ollama: {e}")
        sys.exit(1)


def check_ollama():
    try:
        with urllib.request.urlopen(f"{OLLAMA_URL}/api/tags", timeout=5) as resp:
            data = json.loads(resp.read())
            models = [m["name"] for m in data.get("models", [])]
            if not any(MODEL in m for m in models):
                print(f"ОШИБКА: модель '{MODEL}' не найдена.")
                sys.exit(1)
            print(f"Ollama OK  |  модель '{MODEL}' доступна\n")
    except urllib.error.URLError:
        print(f"ОШИБКА: Ollama не запущена ({OLLAMA_URL}).")
        sys.exit(1)


def get_score(query: str, embedder, reranker, client, collection) -> tuple[float, str]:
    vector = embedder.encode(f"query: {query}", normalize_embeddings=True).tolist()
    hits = client.search(collection_name=collection, query_vector=vector,
                         limit=20, with_payload=True)
    if not hits:
        return -99.0, "—"
    pairs = [(query, h.payload.get("text", "")) for h in hits]
    scores = reranker.predict(pairs)
    idx = int(scores.argmax())
    return float(scores[idx]), hits[idx].payload.get("title", "—")[:60]


